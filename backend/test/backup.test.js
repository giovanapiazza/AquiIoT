const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { join } = require('node:path')
const { tmpdir } = require('node:os')
const { spawnSync } = require('node:child_process')
const { openDatabase } = require('../database')
const { createRepository } = require('../repository')

test('backup mantém dados confirmados no WAL e protege backup existente', t => {
  const directory = mkdtempSync(join(tmpdir(), 'aquiiot-backup-'))
  const source = join(directory, 'source.sqlite')
  const target = join(directory, 'backups', 'snapshot.sqlite')
  const db = openDatabase(source)
  t.after(() => { db.close(); rmSync(directory, { recursive: true, force: true }) })
  createRepository(db).recordLocation({ dispositivo: 'TAG', setor: 'Laboratório', temperatura: 20 })
  const run = () => spawnSync(process.execPath, [join(__dirname, '../database/backup.js'), target], { env: { ...process.env, DATABASE_PATH: source }, encoding: 'utf8' })
  const first = run()
  assert.equal(first.status, 0, first.stderr)
  const copy = openDatabase(target)
  try {
    assert.equal(createRepository(copy).getDevice('TAG').setor, 'Laboratório')
    assert.equal(copy.prepare('PRAGMA integrity_check').get().integrity_check, 'ok')
    assert.deepEqual(copy.prepare('PRAGMA foreign_key_check').all(), [])
  } finally { copy.close() }
  const duplicate = run()
  assert.notEqual(duplicate.status, 0)
  assert.match(duplicate.stderr, /Destino já existe/)
})
